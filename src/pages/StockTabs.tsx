export function RatiosTab({ fin, summary, financial }: { fin: Fin; summary: Summary | null; financial: boolean }) {
  const rows = useMemo(() => (fin.data ? yearlyRatios(fin.data.annual) : []), [fin.data]);
  if (fin.loading && !fin.data) return <Loading label="Loading financial statements…" height={200} />;
  if (fin.error) return <ErrorNote error={fin.error} retry={fin.reload} />;
  if (!rows.length) return <Note kind="warn">No annual statements are available, so ratios cannot be worked out.</Note>;
  const shown = rows.slice(-5);
  const last = shown[shown.length - 1];
  const checks = qualityChecks(rows).filter((c) => !financial || !['Profits backed by cash', 'Generates free cash', 'Debt falling relative to equity', 'Interest comfortably covered'].includes(c.label));
  const passed = checks.filter((c) => c.pass === true).length;
  const known = checks.filter((c) => c.pass !== null).length;
  const fmt = (v: number | null, kind: 'pct' | 'x' | 'growth') => (v === null ? '—' : kind === 'x' ? times(v, 2) : kind === 'growth' ? signedPct(v) : pct(v));
  const price = summary?.price?.regularMarketPrice;
  const sameCcy = summary && (!summary.fin.financialCurrency || summary.fin.financialCurrency === summary.price.currency);
  const mcap = summary?.price?.marketCap;

  return (
    <div className="stack">
      <div className="grid cols-2">
        <Card title="Quality checklist" sub={`${passed} of ${known} passed, latest year against the one before`}>
          <div className="stack" style={{ gap: 7 }}>
            {checks.map((c) => (
              <div key={c.label} className="row" style={{ flexWrap: 'nowrap', alignItems: 'flex-start' }}>
                <span className={'badge ' + (c.pass === null ? '' : c.pass ? 'pos' : 'neg')} style={{ minWidth: 46, textAlign: 'center' }}>
                  {c.pass === null ? 'n/a' : c.pass ? 'Yes' : 'No'}
                </span>
                <span>
                  <span className="strong">{c.label}</span> <span className="small muted">{c.why}</span>
                </span>
              </div>
            ))}
          </div>
          <p className="tiny muted mt-s">A checklist catches obvious problems; it cannot tell you whether the price is right or the business will stay good.</p>
        </Card>
        <Card title="Why is return on equity what it is?" sub={`DuPont breakdown, year to ${monthYear(last.date)}`}>
          {last.netMargin !== null && last.assetTurnover !== null && last.equityMultiplier !== null ? (
            <>
              <div className="formula" style={{ whiteSpace: 'pre-wrap' }}>
                {`ROE ${pct(last.roe)}  =  net margin ${pct(last.netMargin)}  ×  asset turnover ${num(last.assetTurnover, 2)}  ×  leverage ${num(last.equityMultiplier, 2)}`}
              </div>
              <ul className="small dim" style={{ paddingLeft: 18, margin: '10px 0 0' }}>
                <li><b>Net margin</b>: profit kept from each rupee of sales.</li>
                <li><b>Asset turnover</b>: sales generated per rupee of assets.</li>
                <li><b>Leverage</b>: assets per rupee of shareholders' money. Above about 2–3 for a non-financial company, a good part of the ROE comes from borrowing rather than from the business.</li>
              </ul>
            </>
          ) : (
            <p className="muted">Not enough balance-sheet data for this breakdown.</p>
          )}
          {sameCcy && price && mcap && last.fcf !== null && last.netIncome !== null && (
            <dl className="kv mt">
              <dt>Earnings yield <Tip text="Net profit ÷ market value: the inverse of the P/E ratio. Compare it with the yield on a government bond." /></dt>
              <dd>{pct(last.netIncome / mcap, 2)}</dd>
              <dt>Free cash flow yield <Tip text="Free cash flow ÷ market value: the cash the business generates for each rupee of its market price." /></dt>
              <dd>{pct(last.fcf / mcap, 2)}</dd>
            </dl>
          )}
        </Card>
      </div>
      <Card title="Ratios year by year" sub="worked out from the statements on the Financials tab, using year-end balances" flush>
        <div className="tbl-wrap">
          <table className="tbl">
            <thead>
              <tr>
                <th>Ratio</th>
                {shown.map((r) => (
                  <th className="r" key={r.date}>
                    {monthYear(r.date)}
                  </th>
                ))}
              </tr>
            </thead>
            <tbody>
              {RATIO_ROWS.filter((r) => !(financial && r.lender === false)).filter((r) => shown.some((y) => y[r.key] !== null)).map((r) => (
                <tr key={r.key}>
                  <td>
                    {r.label} <Tip text={r.tip} />
                  </td>
                  {shown.map((y) => {
                    const v = y[r.key] as number | null;
                    return (
                      <td key={y.date} className={'r ' + (r.kind === 'growth' ? tone(v) : '')}>
                        {fmt(v, r.kind)}
                      </td>
                    );
                  })}
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </Card>
      <div className="grid cols-2">
        <Card title="Margins over time">
          <LineChart
            x={rows.map((r) => r.date.slice(0, 4))}
            series={[
              ...(financial ? [] : [{ name: 'Operating margin', values: rows.map((r) => r.operatingMargin) }]),
              { name: 'Net margin', values: rows.map((r) => r.netMargin), color: 'var(--s3)' },
            ]}
            yFormat={(v) => pct(v, 0)}
            zeroLine
            height={210}
          />
        </Card>
        <Card title="Return on equity over time">
          <BarChart data={rows.map((r) => ({ label: r.date.slice(0, 4), value: r.roe ?? NaN, note: 'ROE' }))} yFormat={(v) => pct(v, 0)} height={210} />
        </Card>
      </div>
      <p className="plain">
        In plain words: a good business usually shows steady growth, healthy margins, a return on equity well above what a deposit pays, little debt, and profits that arrive as cash. One good year proves nothing: look for consistency
        across the columns.
      </p>
    </div>
  );
}

/* ---------- Returns & risk ---------- */

const PERIODS: { label: string; days: number }[] = [
  { label: '1 month', days: 30 },
  { label: '3 months', days: 91 },
  { label: '6 months', days: 182 },
  { label: '1 year', days: 365 },
  { label: '3 years', days: 1096 },
  { label: '5 years', days: 1826 },
  { label: '10 years', days: 3652 },
];

export function ReturnsTab({ symbol, benchmark }: { symbol: string; benchmark: string }) {
  const rf = useStore((s) => s.settings.riskFree);
  const data = useAsync(async () => {
    const [a, b] = await Promise.all([getChart(symbol, 'max', '1d'), symbol === benchmark ? Promise.resolve(null) : getChart(benchmark, 'max', '1d').catch(() => null)]);
    return { stock: toDaily(a), bench: b ? toDaily(b) : null };
  }, [symbol, benchmark]);

  const calc = useMemo(() => {
    if (!data.data) return null;
    const { stock, bench } = data.data;
    const n = stock.dates.length;
    if (n < 5) return null;
    const lastDate = stock.dates[n - 1];
    const lastMs = Date.parse(lastDate);
    const at = (s: { dates: string[]; adj: number[] }, ms: number) => {
      // last observation on or before the target date
      let lo = 0;
      let hi = s.dates.length - 1;
      if (Date.parse(s.dates[0]) > ms) return null;
      while (lo < hi) {
        const mid = (lo + hi + 1) >> 1;
        if (Date.parse(s.dates[mid]) <= ms) lo = mid;
        else hi = mid - 1;
      }
      return s.adj[lo];
    };
    const ret = (s: { dates: string[]; adj: number[] }, days: number) => {
      const start = at(s, lastMs - days * 86_400_000);
      const end = at(s, lastMs);
      if (start === null || end === null || !(start > 0)) return null;
      const total = end / start - 1;
      return days > 366 ? Math.pow(1 + total, 365.25 / days) - 1 : total;
    };
    const ytdStart = Date.parse(lastDate.slice(0, 4) + '-01-01') - 86_400_000;
    const ytd = (s: { dates: string[]; adj: number[] }) => {
      const a = at(s, ytdStart);
      const b = at(s, lastMs);
      return a && b ? b / a - 1 : null;
    };
    const table = [
      ...PERIODS.slice(0, 3).map((p) => ({ label: p.label, stock: ret(stock, p.days), bench: bench ? ret(bench, p.days) : null, annual: false })),
      { label: 'This year so far', stock: ytd(stock), bench: bench ? ytd(bench) : null, annual: false },
      ...PERIODS.slice(3).map((p) => ({ label: p.label, stock: ret(stock, p.days), bench: bench ? ret(bench, p.days) : null, annual: p.days > 366 })),
    ];
    // risk over the last five years (or everything, if shorter)
    const from = new Date(lastMs - 1826 * 86_400_000).toISOString().slice(0, 10);
    const i0 = Math.max(0, stock.dates.findIndex((d) => d >= from));
    const dates = stock.dates.slice(i0);
    const levels = stock.adj.slice(i0);
    const perf = performance(dates, levels, rf);
    let reg = null;
    let benchPerf = null;
    let idx: { dates: string[]; stock: number[]; bench: number[] } | null = null;
    if (bench) {
      const al = align([{ ...stock, dates, close: levels, adj: levels }, bench], 'adj');
      if (al.dates.length > 30) {
        const sr: number[] = [];
        const br: number[] = [];
        for (let t = 1; t < al.matrix.length; t++) {
          sr.push(al.matrix[t][0] / al.matrix[t - 1][0] - 1);
          br.push(al.matrix[t][1] / al.matrix[t - 1][1] - 1);
        }
        reg = regress(sr, br, 252, rf);
        benchPerf = performance(al.dates, al.matrix.map((r) => r[1]), rf);
        idx = { dates: al.dates, stock: al.matrix.map((r) => (r[0] / al.matrix[0][0]) * 100), bench: al.matrix.map((r) => (r[1] / al.matrix[0][1]) * 100) };
      }
    }
    const full = performance(stock.dates, stock.adj, rf);
    return { table, perf, reg, benchPerf, idx, dates, dd: drawdown(levels).series, full, first: stock.dates[0] };
  }, [data.data, rf]);

  if (data.loading && !data.data) return <Loading label="Loading full price history…" height={200} />;
  if (data.error) return <ErrorNote error={data.error} retry={data.reload} />;
  if (!calc || !calc.perf) return <Note kind="warn">Not enough price history to measure returns and risk.</Note>;
  const { perf, reg, benchPerf } = calc;
  const bn = benchmarkName(benchmark);
  const hasBench = !!data.data?.bench;
  return (
    <div className="stack">
      <Card title="Returns" sub="including dividends; periods over one year are shown per year" flush>
        <div className="tbl-wrap">
          <table className="tbl">
            <thead>
              <tr>
                <th>Period</th>
                <th className="r">{shortSymbol(symbol)}</th>
                {hasBench && <th className="r">{bn}</th>}
                {hasBench && <th className="r">Difference</th>}
              </tr>
            </thead>
            <tbody>
              {calc.table.map((r) => (
                <tr key={r.label}>
                  <td>
                    {r.label}
                    {r.annual ? <span className="muted small"> (per year)</span> : ''}
                  </td>
                  <td className={'r strong ' + tone(r.stock)}>{signedPct(r.stock)}</td>
                  {hasBench && <td className={'r ' + tone(r.bench)}>{signedPct(r.bench)}</td>}
                  {hasBench && <td className={'r ' + (r.stock !== null && r.bench !== null ? tone(r.stock - r.bench) : '')}>{r.stock !== null && r.bench !== null ? signedPct(r.stock - r.bench) : '—'}</td>}
                </tr>
              ))}
            </tbody>
          </table>
        </div>
        <p className="tiny muted" style={{ padding: '8px 14px' }}>
          “—” means the history does not go back that far (first price: {fmtDate(calc.first)}). {hasBench && marketOf(benchmark) === 'IN' ? 'The index shown is a price index, so its returns leave out dividends (roughly 1–1.5% a year for the NIFTY 50).' : ''}
        </p>
      </Card>
      <Stats>
        <Stat label="Volatility" tip="Annualised standard deviation of daily returns over the period: a typical year's swing." value={pct(perf.volatility)} sub={benchPerf ? `${bn}: ${pct(benchPerf.volatility)}` : undefined} />
        <Stat label={`Beta vs ${bn}`} tip="How much the share has moved for each 1% move in the index, from daily returns." value={reg ? num(reg.beta, 2) : '—'} sub={reg ? `${pct(reg.r2, 0)} of its moves explained by the market` : undefined} />
        <Stat label="Deepest fall" value={pct(perf.maxDrawdown)} tone="neg" sub={`${fmtDate(perf.drawdownPeak)} → ${fmtDate(perf.drawdownTrough)}`} />
        <Stat label="Sharpe ratio" tip={`Return above the risk-free rate (${pct(rf)}) per unit of volatility.`} value={num(perf.sharpe, 2)} />
        <Stat label="Best / worst year" value={perf.bestYear && perf.worstYear ? `${signedPct(perf.bestYear.ret, 0)} / ${signedPct(perf.worstYear.ret, 0)}` : '—'} sub={perf.bestYear && perf.worstYear ? `${perf.bestYear.year} / ${perf.worstYear.year}` : 'needs full calendar years'} />
      </Stats>
      <p className="tiny muted">Risk figures cover {fmtDate(perf.start)} to {fmtDate(perf.end)} (up to five years).</p>
      {calc.idx && (
        <Card title={`Growth of 100 against ${bn}`}>
          <LineChart x={calc.idx.dates} series={[{ name: shortSymbol(symbol), values: calc.idx.stock }, { name: bn, values: calc.idx.bench, color: 'var(--text-3)' }]} yFormat={(v) => num(v, 0)} height={280} />
        </Card>
      )}
      <div className="grid cols-2">
        <Card title="Return by calendar year">
          <BarChart data={(calc.full?.yearly ?? []).slice(-15).map((y) => ({ label: String(y.year).slice(2) + (y.partial ? '*' : ''), value: y.ret, note: `${y.year}${y.partial ? ' (part year)' : ''}` }))} signed yFormat={(v) => pct(v, 0)} height={220} />
        </Card>
        <Card title="Falls from the previous peak">
          <LineChart x={calc.dates} series={[{ name: 'Drawdown', values: calc.dd }]} yFormat={(v) => pct(v, 0)} area yMax={0} height={220} hideLegend />
        </Card>
      </div>
    </div>
  );
}

/* ---------- Dividends ---------- */

export function DividendsTab({ symbol, summary, currency }: { symbol: string; summary: Summary | null; currency: string | null }) {
  const data = useAsync(() => getChart(symbol, 'max', '1d'), [symbol]);
  if (data.loading && !data.data) return <Loading label="Loading dividend history…" height={160} />;
  if (data.error) return <ErrorNote error={data.error} retry={data.reload} />;
  const c = data.data;
  if (!c) return null;
  const events = c.div.map(([t, amount]) => ({ date: chartDates({ t: [t], gmtoffset: c.gmtoffset })[0], amount }));
  const byYear = new Map<string, number>();
  for (const e of events) byYear.set(e.date.slice(0, 4), (byYear.get(e.date.slice(0, 4)) ?? 0) + e.amount);
  const years = [...byYear.entries()].sort((a, b) => (a[0] < b[0] ? -1 : 1));
  const thisYear = String(new Date().getFullYear());
  const full = years.filter(([y]) => y !== thisYear);
  const growth = full.length >= 6 && full[full.length - 6][1] > 0 ? Math.pow(full[full.length - 1][1] / full[full.length - 6][1], 1 / 5) - 1 : null;
  const splits = c.split.map(([t, a, b]) => ({ date: chartDates({ t: [t], gmtoffset: c.gmtoffset })[0], ratio: a / b }));
  const d = summary?.detail ?? {};
  if (!events.length) {
    return (
      <Card>
        <Empty title="No dividends on record">
          <p>The data provider has no dividend payments for {symbol}. Many growing companies reinvest all their profit instead of paying it out.</p>
        </Empty>
      </Card>
    );
  }
  return (
    <div className="stack">
      <Stats>
        <Stat label="Dividend yield" tip="Yearly dividend ÷ current price." value={typeof d.dividendYield === 'number' ? pct(d.dividendYield, 2) : '—'} />
        <Stat label="Yearly dividend per share" value={d.dividendRate ? num(d.dividendRate, 2) : '—'} sub={currency ?? ''} />
        <Stat label="Payout ratio" tip="Share of profit paid out. Above 100% means the dividend exceeds profit and may not last." value={pct(d.payoutRatio, 0)} tone={d.payoutRatio > 1 ? 'neg' : ''} />
        <Stat label="5-year dividend growth" tip="Compound yearly growth in dividends per share over the last five full calendar years." value={growth !== null ? signedPct(growth) : '—'} tone={tone(growth)} sub="per year" />
        <Stat label="Average yield, 5 years" value={typeof d.fiveYearAvgDividendYield === 'number' ? `${num(d.fiveYearAvgDividendYield, 2)}%` : '—'} />
      </Stats>
      <div className="grid cols-2">
        <Card title="Dividends per share by calendar year" sub={`${currency ?? ''}, adjusted for splits and bonuses`}>
          <BarChart data={years.slice(-15).map(([y, v]) => ({ label: y.slice(2) + (y === thisYear ? '*' : ''), value: v, note: y + (y === thisYear ? ' (so far)' : '') }))} yFormat={(v) => num(v, v < 10 ? 2 : 0)} height={230} />
        </Card>
        <Card title="Recent payments" flush>
          <div className="tbl-wrap" style={{ maxHeight: 290, overflowY: 'auto' }}>
            <table className="tbl compact">
              <thead>
                <tr>
                  <th>Ex-dividend date</th>
                  <th className="r">Per share ({currency ?? ''})</th>
                </tr>
              </thead>
              <tbody>
                {[...events].reverse().slice(0, 40).map((e) => (
                  <tr key={e.date + e.amount}>
                    <td>{fmtDate(e.date)}</td>
                    <td className="r">{num(e.amount, 2)}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </Card>
      </div>
      {splits.length > 0 && (
        <Card title="Splits and bonus issues">
          <div className="chips">
            {splits.map((s) => (
              <span className="chip" key={s.date}>
                {fmtDate(s.date)}: 1 share became {num(s.ratio, s.ratio % 1 ? 3 : 0)}
              </span>
            ))}
          </div>
        </Card>
      )}
      <p className="plain">In plain words: you must own the share before the ex-dividend date to receive that payment. A high yield is not automatically good: it can simply mean the price has fallen because the market doubts the dividend will last.</p>
    </div>
  );
}

/* ---------- Peers ---------- */

export function PeersTab({ symbol, summary }: { symbol: string; summary: Summary | null }) {
  const industry: string | undefined = summary?.profile?.industry;
  const market = marketOf(symbol) === 'IN' ? (symbol.endsWith('.BO') ? 'BSE' : 'NSE') : marketOf(symbol) === 'UK' ? 'UK' : 'US';
  const data = useAsync(
    industry
      ? async () => {
          const res = await screen({ market, industry: industry.replace(/ - /g, '—'), sort: 'marketCap', size: 12 });
          const list: Quote[] = res.quotes.filter((q) => q.symbol !== symbol).slice(0, 10);
          const symbols = [symbol, ...list.map((q) => q.symbol)];
          const funda = await getFundamentals(symbols);
          return { list, funda, total: res.total };
        }
      : null,
    [symbol, industry, market],
  );
  if (!summary) return <Loading label="Loading company details…" />;
  if (!industry) return <Note kind="warn">The data provider has no industry classification for {symbol}, so peers cannot be found automatically. Use Compare stocks to choose your own.</Note>;
  if (data.loading && !data.data) return <Loading label={`Finding other ${industry} companies…`} height={160} />;
  if (data.error) return <ErrorNote error={data.error} retry={data.reload} />;
  if (!data.data) return null;
  const rows = [symbol, ...data.data.list.map((q) => q.symbol)].map((s) => data.data!.funda[s]).filter((f): f is Fundamentals => !!f?.ok);
  const med = (get: (f: Fundamentals) => number | null | undefined) => {
    const v = rows.map(get).filter((x): x is number => typeof x === 'number' && Number.isFinite(x) && x > 0).sort((a, b) => a - b);
    return v.length ? (v.length % 2 ? v[(v.length - 1) / 2] : (v[v.length / 2 - 1] + v[v.length / 2]) / 2) : null;
  };
  return (
    <div className="stack">
      <Card title={`Largest ${industry} companies on ${market}`} sub={`${data.data.total} in the industry; the ${rows.length - 1} biggest shown`} right={<Link className="btn sm" to={`/compare?symbols=${rows.slice(0, 5).map((r) => encodeURIComponent(r.symbol)).join(',')}`}>Open in Compare</Link>} flush>
        <div className="tbl-wrap">
          <table className="tbl">
            <thead>
              <tr>
                <th>Company</th>
                <th className="r">Market value</th>
                <th className="r">P/E</th>
                <th className="r">P/B</th>
                <th className="r">EV/EBITDA</th>
                <th className="r">ROE</th>
                <th className="r">Net margin</th>
                <th className="r">Sales growth</th>
                <th className="r">Debt/equity</th>
                <th className="r">Div. yield</th>
              </tr>
            </thead>
            <tbody>
              {rows.map((f) => (
                <tr key={f.symbol} style={f.symbol === symbol ? { background: 'var(--accent-soft)' } : undefined}>
                  <td>
                    <Link to={`/stock/${encodeURIComponent(f.symbol)}`} className={f.symbol === symbol ? 'strong' : ''}>
                      {shortSymbol(f.symbol)}
                    </Link>
                    <span className="sub">{f.name}</span>
                  </td>
                  <td className="r">{compact(f.marketCap, f.currency)}</td>
                  <td className="r">{f.trailingPE ? num(f.trailingPE, 1) : '—'}</td>
                  <td className="r">{f.priceToBook ? num(f.priceToBook, 1) : '—'}</td>
                  <td className="r">{f.evToEbitda ? num(f.evToEbitda, 1) : '—'}</td>
                  <td className="r">{pct(f.roe)}</td>
                  <td className="r">{pct(f.profitMargin)}</td>
                  <td className={'r ' + tone(f.revenueGrowth)}>{signedPct(f.revenueGrowth)}</td>
                  <td className="r">{f.debtToEquity != null ? times(f.debtToEquity, 2) : '—'}</td>
                  <td className="r">{pct(f.dividendYield, 2)}</td>
                </tr>
              ))}
            </tbody>
            <tfoot>
              <tr>
                <td>Median of the group</td>
                <td />
                <td className="r">{num(med((f) => f.trailingPE), 1)}</td>
                <td className="r">{num(med((f) => f.priceToBook), 1)}</td>
                <td className="r">{num(med((f) => f.evToEbitda), 1)}</td>
                <td className="r">{pct(med((f) => f.roe))}</td>
                <td className="r">{pct(med((f) => f.profitMargin))}</td>
                <td className="r">{pct(med((f) => f.revenueGrowth))}</td>
                <td className="r">{times(med((f) => f.debtToEquity), 2)}</td>
                <td className="r">{pct(med((f) => f.dividendYield), 2)}</td>
              </tr>
            </tfoot>
          </table>
        </div>
      </Card>
      <p className="plain">
        In plain words: a ratio means little on its own. A P/E of 30 is cheap for a fast-growing consumer brand and expensive for a steel maker. Comparing a company with others in the same industry shows whether the market rates it
        above or below its rivals, and the quality columns (ROE, margin, growth, debt) hint at whether that is deserved.
      </p>
    </div>
  );
}
