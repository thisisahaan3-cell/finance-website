export function FinancialsTab({ fin, financial }: { fin: Fin; financial: boolean }) {
  const [period, setPeriod] = useState<'annual' | 'quarterly'>('annual');
  if (fin.loading && !fin.data) return <Loading label="Loading financial statements…" height={200} />;
  if (fin.error) return <ErrorNote error={fin.error} retry={fin.reload} />;
  const f = fin.data;
  if (!f) return null;
  const t = f[period];
  const inr = f.currency === 'INR';
  const unit = inr ? 1e7 : 1e6;
  const unitLabel = inr ? '₹ crore' : `${f.currency ?? ''} million`;
  const cols = t.dates.map((_, i) => i).slice(-(period === 'annual' ? 5 : 6));
  const has = (key: string) => t.items[key]?.some((v) => typeof v === 'number');
  const rev = cols.map((i) => t.items.TotalRevenue?.[i] ?? null);
  const ni = cols.map((i) => t.items.NetIncome?.[i] ?? null);
  const revCagr = period === 'annual' ? seriesCagr(t.items.TotalRevenue ?? [], t.dates) : null;
  const niCagr = period === 'annual' ? seriesCagr(t.items.NetIncome ?? [], t.dates) : null;

  if (!t.dates.length) return <Note kind="warn">No {period} statements are available for this company from the data provider.</Note>;
  return (
    <div className="stack">
      <div className="row between">
        <span className="small muted">
          Figures in <b>{unitLabel}</b> (per-share items in {currencySymbol(f.currency).trim() || f.currency}). Financial years end on the dates shown.
        </span>
        <Seg options={[{ value: 'annual', label: 'Yearly' }, { value: 'quarterly', label: 'Quarterly' }]} value={period} onChange={setPeriod} label="Statement period" />
      </div>
      {financial && <Note>Banks and lenders report differently: there is no gross profit or EBITDA, and “debt” includes customer deposits. Rows that do not apply are left out.</Note>}
      <div className="grid cols-2">
        <Card title="Revenue and net profit" sub={unitLabel}>
          <StackedColumns
            categories={cols.map((i) => monthYear(t.dates[i]))}
            series={[
              { name: 'Net profit', values: ni.map((v) => Math.max(0, (v ?? 0) / unit)), color: 'var(--s3)' },
              { name: 'Revenue kept by costs and tax', values: rev.map((v, k) => Math.max(0, ((v ?? 0) - Math.max(0, ni[k] ?? 0)) / unit)), color: 'var(--s1)' },
            ]}
            yFormat={(v) => num(v, 0)}
            height={220}
          />
          <p className="tiny muted">The whole column is revenue; the green part is what remained as profit.</p>
        </Card>
        <Card title="Growth over the years shown">
          <Stats>
            <Stat label="Revenue growth per year" value={revCagr ? signedPct(revCagr.rate) : '—'} tone={tone(revCagr?.rate)} sub={revCagr ? `over ${num(revCagr.years, 0)} years` : period === 'quarterly' ? 'switch to yearly' : 'not enough data'} />
            <Stat label="Profit growth per year" value={niCagr ? signedPct(niCagr.rate) : '—'} tone={tone(niCagr?.rate)} sub={niCagr ? `over ${num(niCagr.years, 0)} years` : period === 'quarterly' ? 'switch to yearly' : 'not measurable (loss in a base year)'} />
          </Stats>
          <p className="small muted mt-s">
            Compound annual growth between the first and last year shown. Profit growing faster than revenue means margins are widening; slower means costs are rising faster than sales.
          </p>
        </Card>
      </div>
      {STATEMENTS.map((st) => {
        const rows = st.rows.filter(([key]) => has(key));
        if (!rows.length) return null;
        return (
          <Card key={st.title} title={st.title} sub={st.note} flush>
            <div className="tbl-wrap">
              <table className="tbl">
                <thead>
                  <tr>
                    <th>{unitLabel}</th>
                    {cols.map((i) => (
                      <th className="r" key={i}>
                        {monthYear(t.dates[i])}
                      </th>
                    ))}
                  </tr>
                </thead>
                <tbody>
                  {rows.map(([key, label, tip]) => {
                    const perShare = key.endsWith('EPS');
                    const count = key === 'OrdinarySharesNumber';
                    const bold = ['TotalRevenue', 'NetIncome', 'TotalAssets', 'StockholdersEquity', 'OperatingCashFlow', 'FreeCashFlow'].includes(key);
                    return (
                      <tr key={key}>
                        <td className={bold ? 'strong' : ''}>
                          {label} {tip && <Tip text={tip} />}
                        </td>
                        {cols.map((i) => {
                          const v = t.items[key]?.[i];
                          return (
                            <td key={i} className={'r ' + (bold ? 'strong ' : '') + (typeof v === 'number' && v < 0 ? 'neg' : '')}>
                              {typeof v !== 'number' ? '—' : perShare ? num(v, 2) : count ? `${num(v / 1e7, 2)} Cr` : num(v / unit, 0, f.currency)}
                            </td>
                          );
                        })}
                      </tr>
                    );
                  })}
                </tbody>
              </table>
            </div>
          </Card>
        );
      })}
      {f.ttmDate && <p className="tiny muted">Latest twelve months to {fmtDate(f.ttmDate)}: revenue {compact(f.ttm.TotalRevenue, f.currency)}, net profit {compact(f.ttm.NetIncome, f.currency)}.</p>}
    </div>
  );
}

